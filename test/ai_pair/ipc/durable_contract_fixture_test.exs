  # --- the byte comparison ---------------------------------------------------

  defp assert_fixture(name, frame) do
    decoded = Jason.decode!(frame)
    substituted = substitute(decoded)
    expected = @fixture_dir |> Path.join(name) |> File.read!()

    assert Jason.encode!(substituted) <> "\n" == expected,
           "#{name}: bytes differ\n  produced: #{Jason.encode!(substituted)}\n  fixture:  #{String.trim_trailing(expected)}"

    assert Jason.decode!(expected) == substituted, "#{name}: the decoded objects differ"

    :persistent_term.put(
      {__MODULE__, :produced},
      MapSet.put(:persistent_term.get({__MODULE__, :produced}), name)
    )

    decoded
  end

  # Each dynamic member's exact value is asserted BEFORE it is replaced, so a
  # placeholder can never stand in for a value the producer got wrong.
  defp substitute(frame) do
    Map.new(frame, fn
      {"pane_id", value} ->
        assert value == @pane
        {"pane_id", "<pane_id>"}

      {"agent", value} ->
        assert value == @agent
        {"agent", "<agent>"}

      {"classifier", value} ->
        assert value == @classifier
        {"classifier", "<classifier>"}

      {"state", value} ->
        assert value in ~w(idle busy dialog dead unknown)
        {"state", "<state>"}

      {"coordinator_error", value} ->
        assert is_binary(value) and value != ""
        {"coordinator_error", "<detail>"}

      other ->
        other
    end)
  end

  # --- the daemon ------------------------------------------------------------

  defp legacy_server!(c) do
    Application.put_env(:ai_pair, :durable_attachments, false)
    start_server!(c, [])
  end

  defp durable_server!(c) do
    Application.put_env(:ai_pair, :durable_attachments, true)
    start_server!(c, boot_generation: @boot_generation)
  end

  defp start_server!(c, extra) do
    name = :"s9_fixture_ipc_#{System.unique_integer([:positive])}"
    opts = [inbox: c.root, name: name] ++ extra
    {:ok, pid} = ReceiptBackedIPCServer.start_link(opts)
    on_exit(fn -> stop_quietly(pid) end)
    pid
  end

  defp stop_quietly(pid) do
    if Process.alive?(pid) do
      try do
        GenServer.stop(pid, :normal, 1_000)
      catch
        :exit, _reason -> :ok
      end
    end
  end

  defp request(c, payload) do
    {:ok, client} =
      :gen_tcp.connect({:local, c.sock}, 0, [:binary, {:active, false}, {:packet, 4}], 1_000)

    :ok = :gen_tcp.send(client, Jason.encode!(payload))
    {:ok, frame} = :gen_tcp.recv(client, 0, @recv_timeout_ms)
    :gen_tcp.close(client)
    frame
  end

  defp durable_attach do
    %{"cmd" => "attach_pane", "pane_id" => @pane, "agent" => @agent, "durable" => true}
  end

  # --- collaborators ---------------------------------------------------------

  # The whole durable attach context: a durable server, a ledger, a binding and
  # a scripted adapter. The store is chosen per row.
  defp durable_attach_context!(c, steps) do
    durable_server!(c)
    coordinator!()
    bind!(c.root)
    scripted_tmux!(steps)
  end

  # The same, plus a healthy real store: the store lookup precedes the census in
  # the contract's order, so a census or marker refusal is only reachable once a
  # store owner exists. Every row below asserts nothing was written to it.
  defp refusal_context!(c, steps) do
    durable_attach_context!(c, steps)
    store!(c.root)
  end

  defp coordinator!, do: start_supervised!({Coordinator, []})

  defp coordinator_pid, do: Process.whereis(Coordinator)

  # Stopping the ledger destroys the fence the running body holds. `:normal`
  # rather than a kill, so the guardian's own teardown path runs.
  defp stop_ledger(ledger) do
    ref = Process.monitor(ledger)
    Process.exit(ledger, :shutdown)

    receive do
      {:DOWN, ^ref, :process, ^ledger, _reason} -> :ok
    after
      1_000 -> :ok
    end
  end

  defp hold_fence!(pane) do
    parent = self()

    holder =
      spawn(fn ->
        Coordinator.transaction(pane, fn ->
          send(parent, :held)

          receive do
            :release -> {:ok, :released}
          after
            30_000 -> {:ok, :expired}
          end
        end)
      end)

    assert_receive :held, 5_000
    on_exit(fn -> if Process.alive?(holder), do: send(holder, :release) end)
    holder
  end

  defp bind!(root) do
    Application.put_env(:ai_pair, :project_binding, %{
      project: "s9fixture",
      project_dir: root,
      project_inbox: root
    })
  end

  defp store!(root, opts \\ []) do
    {:ok, pid} = PaneIntentStore.start_link([root: root] ++ opts)
    RouteGuard.own_process(pid)
    on_exit(fn -> stop_quietly(pid) end)
    pid
  end

  defp store_pid(root), do: :global.whereis_name({PaneIntentStore, Path.expand(root)})

  defp fixture_store!(root, script) do
    {:ok, pid} = DurableFixtureStore.start_link(script)
    RouteGuard.own_process(pid)
    :yes = :global.register_name({PaneIntentStore, Path.expand(root)}, pid)
    on_exit(fn -> stop_quietly(pid) end)
    pid
  end

  defp fault_fs!(_c) do
    fs = FaultFs.new()
    {_module, agent} = fs
    RouteGuard.own_process(agent)
    fs
  end

  defp state_dir?([path]), do: String.ends_with?(path, "/state")
  defp state_dir?(_args), do: false

  defp unbind_supervisor do
    if Process.whereis(PaneSupervisor), do: Process.unregister(PaneSupervisor)
    :ok
  end

  defp rebind_supervisor(pid) do
    if Process.whereis(PaneSupervisor) == nil and Process.alive?(pid) do
      Process.register(pid, PaneSupervisor)
    end

    :ok
  end

  defp refute_pane_started do
    assert PaneSupervisor.whereis_pane(@pane) == :error,
           "a pre-effect refusal starts nothing"
  end

  # --- the scripted adapter --------------------------------------------------

  defp scripted_tmux!(steps) do
    {name, _dir} = ScriptedTmux.start!(steps)
    Application.put_env(:ai_pair, :tmux_server, name)
    name
  end

  # A same-owner marker is already present, so `Marker.ensure/3` writes nothing:
  # census, ensure-read, read, fenced census, fenced read.
  defp happy_script(root) do
    [census([row()]), marker(root), marker(root), census([row()]), marker(root)]
  end

  defp census(rows), do: {Enum.map_join(rows, "", &(&1 <> "\n")), 0}

  defp row(overrides \\ []) do
    fields = [
      pane_id: @pane,
      session_id: @session,
      session_name: @session_name,
      window_index: 0,
      pane_index: 0,
      pane_pid: @pane_pid,
      command: @command,
      path: "/private/tmp"
    ]

    # Overridden field by field, in place: `Keyword.merge/2` moves an overridden
    # key to the END of the list, which silently reorders the census columns and
    # makes the adapter refuse the whole row as malformed.
    Enum.map_join(fields, "|", fn {key, default} ->
      to_string(Keyword.get(overrides, key, default))
    end)
  end

  # `show-options -v` prints the value and one newline; the stored value carries
  # none, and the reader trims exactly that. The owner root is the row's own
  # binding, passed explicitly so a script built before `bind!/1` cannot drift.
  defp marker(root, overrides \\ []) do
    value = %{
      "version" => 1,
      "owner_root" => Keyword.get(overrides, :owner_root, root),
      "session_id" => Keyword.get(overrides, :session_id, @session),
      "generation" => Keyword.get(overrides, :generation, @marker_generation)
    }

    {Jason.encode!(value) <> "\n", 0}
  end

  defp absent_marker, do: {"invalid option: @ai_pair_session_incarnation\n", 1, :stderr}

  defp canonical_tmp do
    System.tmp_dir!()
    |> Path.expand()
    |> Path.split()
    |> Enum.reduce("/", fn segment, acc ->
      joined = Path.join(acc, segment)

      case File.read_link(joined) do
        {:ok, "/" <> _rest = absolute} -> absolute
        {:ok, relative} -> Path.expand(Path.join(Path.dirname(joined), relative))
        {:error, _reason} -> joined
      end
    end)
  end
end
