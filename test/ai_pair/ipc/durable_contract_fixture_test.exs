  Produces every reply fixture under `test/fixtures/contracts/ipc/durable` from
  the REAL daemon, over a real unix socket, and compares the bytes.

  Contract: `docs/contracts/durable-attach-detach.org`. Until this slice the
  fixture suite (`test/ai_pair/contracts/durable_ipc_contract_test.exs`) could
  only read the frozen bytes back and check their closed shapes, because no
  producer existed. Every reply fixture is now generated by
  `AiPair.IPC.Server` answering a frame on its socket.

  ## What "compared byte for byte" means here, exactly

  A fixture carries placeholders (`<pane_id>`, `<agent>`, `<classifier>`,
  `<state>`, `<detail>`) where the value is run-dependent. So each row:

    1. decodes the frame the server actually sent;
    2. substitutes each dynamic member, asserting its exact pre-substitution
       value first, so a placeholder can never hide a wrong one;
    3. asserts the re-encoded substituted frame plus one newline equals the
       fixture file's bytes, AND that the fixture decodes to exactly the
       substituted object — the second check is order-independent, so neither
       can pass alone on an accident of member order.

  MEASURED, and stated because it is easy to assume otherwise: the frozen
  fixture bytes are in member-sorted order, which is what the repository's
  encoder emits for a STRING-keyed map. The server builds its replies as
  ATOM-keyed maps, and on this OTP a small map's atom keys iterate in atom-table
  order rather than by name, so the daemon's own frame carries the same members
  in a different order. That is exactly what the contract's "Not promised"
  section allows ("Member order or whitespace in any reply: readers parse JSON
  ... only the decoded object is contractual"), and the row
  "the frozen bytes are the member-sorted encoding of the daemon's own frame"
  below measures the relationship rather than leaving it implied.

  ## Boundary

  No live tmux server. The census and the marker are driven through
  `AiPair.Test.ScriptedTmux`, an owned adapter over a Bash stub that never execs
  tmux, and `AiPair.Test.RouteGuard` holds the `AiPair.Tmux` name for the whole
